    <p>Server iklan pihak ketiga atau jaringan iklan menggunakan teknologi seperti kuki, JavaScript, atau Web Beacon yang digunakan dalam iklan masing-masing dan tautan yang muncul di AizuDemy, yang dikirim langsung ke browser pengguna. Mereka secara otomatis menerima alamat IP Anda saat hal ini terjadi. Teknologi ini digunakan untuk mengukur efektivitas kampanye iklan mereka dan/atau untuk mempersonalisasi konten iklan yang Anda lihat di situs web yang Anda kunjungi.</p>
