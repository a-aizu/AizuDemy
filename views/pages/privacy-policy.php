    <h2>1. Berkas Log (Log Files)</h2>
    <p>AizuDemy mengikuti prosedur standar dalam menggunakan berkas log (log files). Berkas ini mencatat pengunjung saat mereka mengunjungi situs web. Semua perusahaan hosting melakukan ini dan merupakan bagian dari analisis layanan hosting.</p>
    <p>Informasi yang dikumpulkan oleh berkas log mencakup:</p>
    <ul>
      <li>Alamat Protokol Internet (IP Address)</li>
      <li>Jenis browser dan versi perangkat (User-Agent)</li>
      <li>Penyedia Layanan Internet (ISP)</li>
      <li>Stempel tanggal dan waktu kunjungan</li>
      <li>Halaman rujukan/keluar (Referring/Exit Pages)</li>
      <li>Jumlah klik untuk menganalisis tren, mengelola situs, melacak pergerakan pengguna di sekitar situs, dan mengumpulkan informasi demografis</li>
    </ul>
    <p>Informasi tersebut tidak dikaitkan dengan informasi apa pun yang dapat diidentifikasi secara pribadi (PII).</p>

    <h2>2. Kuki dan Suar Web (Cookies and Web Beacons)</h2>
    <p>Seperti situs web profesional lainnya, AizuDemy menggunakan 'cookies'. Kuki digunakan untuk menyimpan informasi termasuk preferensi pengunjung (seperti tema tampilan Dark/Light Mode) dan halaman-halaman di situs web yang diakses atau dikunjungi pengunjung. Informasi tersebut digunakan untuk mengoptimalkan pengalaman pengguna dengan menyesuaikan konten halaman web kami berdasarkan jenis browser pengunjung dan/atau informasi lainnya.</p>

    <h2>3. Kebijakan Google AdSense & Kuki DART</h2>
    <p>Google adalah salah satu vendor pihak ketiga di situs kami. Google juga menggunakan kuki, yang dikenal sebagai kuki DART, untuk menayangkan iklan kepada pengunjung situs kami berdasarkan kunjungan mereka ke <code>aizudemy.net</code> dan situs-situs lain di internet.</p>
    <ul>
      <li>Vendor pihak ketiga, termasuk Google, menggunakan kuki untuk menayangkan iklan berdasarkan kunjungan sebelumnya pengguna ke situs web ini atau situs web lain.</li>
      <li>Penggunaan kuki iklan oleh Google memungkinkan Google dan mitranya untuk menayangkan iklan kepada pengguna Anda berdasarkan kunjungan mereka ke situs Anda dan/atau situs lain di Internet.</li>
      <li>Pengguna dapat menyisih dari periklanan yang dipersonalisasi (opt-out) dengan mengunjungi <a href="https://adssettings.google.com/" target="_blank" rel="noopener noreferrer"><b>Setelan Iklan Google (Google Ads Settings)</b></a>.</li>
      <li>Atau, pengunjung dapat memilih keluar dari penggunaan kuki vendor pihak ketiga untuk iklan yang dipersonalisasi dengan mengunjungi <a href="https://www.aboutads.info/choices/" target="_blank" rel="noopener noreferrer"><b>www.aboutads.info</b></a>.</li>
    </ul>

