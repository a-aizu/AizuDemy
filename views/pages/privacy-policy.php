      <li><b>Hak untuk penghapusan</b> – Anda berhak meminta kami menghapus data pribadi Anda dalam kondisi tertentu.</li>
      <li><b>Hak untuk membatasi pemrosesan</b> – Anda berhak meminta kami membatasi pemrosesan data pribadi Anda.</li>
