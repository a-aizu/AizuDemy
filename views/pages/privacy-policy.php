    <h2>5. Kebijakan Privasi Pihak Ketiga</h2>
    <p>Kebijakan Privasi AizuDemy tidak berlaku untuk pengiklan atau situs web lain. Oleh karena itu, kami menyarankan Anda untuk berkonsultasi dengan masing-masing Kebijakan Privasi dari server iklan pihak ketiga ini untuk informasi lebih terperinci. Ini mungkin mencakup praktik dan instruksi mereka tentang cara menyisih dari opsi tertentu.</p>
    <p>Anda dapat memilih untuk menonaktifkan kuki melalui opsi browser individu Anda. Untuk mengetahui informasi lebih rinci tentang manajemen kuki dengan browser web tertentu, informasi tersebut dapat ditemukan di situs web masing-masing browser.</p>

